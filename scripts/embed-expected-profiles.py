#!/usr/bin/env python3
"""Embeds fixtures/expected-profiles.json, unchanged, in CaveKit and the Kotlin core.

Both apps read the bundled "what to expect" profiles offline from the same text:
  python3 scripts/embed-expected-profiles.py           # write the two source files
  python3 scripts/embed-expected-profiles.py --check   # fail if they are not up to date
The tests of both platforms also check that the embedded text is the fixture.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "fixtures" / "expected-profiles.json"
SWIFT = ROOT / "apple/Packages/CaveKit/Sources/CaveKit/ExpectedProfilesData.swift"
KOTLIN = ROOT / "android/core/src/main/kotlin/app/encave/core/ExpectedProfilesData.kt"
HEADER = "Generated by scripts/embed-expected-profiles.py from fixtures/expected-profiles.json: do not edit."


def chunks(text, size=12000):
    """Pieces cut at line ends: a Kotlin string constant holds at most 65535 bytes."""
    out, current = [], ""
    for line in text.splitlines(keepends=True):
        if current and len((current + line).encode()) > size:
            out.append(current)
            current = ""
        current += line
    if current:
        out.append(current)
    return out


def swift(text):
    if '"""#' in text:
        sys.exit("the fixture holds a sequence a Swift raw string cannot")
    return f'// {HEADER}\n\nextension ExpectedProfiles {{\n    static let json = #"""\n{text}"""#\n}}\n'


def kotlin(text):
    if "$" in text or '"""' in text:
        sys.exit("the fixture holds a character a Kotlin raw string cannot")
    parts = ",\n".join(f'    """{c}"""' for c in chunks(text))
    return (f"// {HEADER}\npackage app.encave.core\n\n"
            f"/** The text of fixtures/expected-profiles.json, in pieces under the size of a string constant. */\n"
            f"internal val expectedProfilesJson: String = listOf(\n{parts},\n).joinToString(\"\")\n")


def main():
    text = FIXTURE.read_text(encoding="utf-8")
    files = {SWIFT: swift(text), KOTLIN: kotlin(text)}
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, c in files.items() if not p.exists() or p.read_text(encoding="utf-8") != c]
        if stale:
            sys.exit("not up to date, run scripts/embed-expected-profiles.py: " + ", ".join(stale))
        print("Embedded profiles are up to date.")
        return
    for path, content in files.items():
        path.write_text(content, encoding="utf-8")
    print("Wrote", ", ".join(str(p.relative_to(ROOT)) for p in files))


main()
